// Public combined list: curated + auto-generated sentences.
// The auto-generated ones are produced by `scripts/generate-sentences.mjs`
// from curated vocab pools so the test rotates through many items.
export const SENTENCES: SentenceItem[] = [
  ...CURATED_SENTENCES,
  ...GENERATED_SENTENCES,
];

export function sentencesByLevel(level: 1 | 2 | 3 | 4 | 5): SentenceItem[] {
  return SENTENCES.filter((s) => s.level === level);
}

export function filterByAvailableVocab(
  level: 1 | 2 | 3 | 4 | 5,
  availableKanji: Set<string>
): SentenceItem[] {
  const pool = sentencesByLevel(level);
  // Sentence eligible if at least 50% of its vocabKanji are in availableKanji
  const eligible = pool.filter((s) => {
    if (s.vocabKanji.length === 0) return true;
    const matched = s.vocabKanji.filter((k) => availableKanji.has(k)).length;
    return matched / s.vocabKanji.length >= 0.5;
  });
  return eligible.length > 0 ? eligible : pool;
}
